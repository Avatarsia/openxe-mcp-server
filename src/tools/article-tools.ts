import { z } from "zod";
import { zodToJsonSchema } from "zod-to-json-schema";
import { OpenXEClient } from "../client/openxe-client.js";

interface ToolDefinition {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
  annotations?: {
    title?: string;
    readOnlyHint?: boolean;
    destructiveHint?: boolean;
    idempotentHint?: boolean;
    openWorldHint?: boolean;
  };
}

interface ToolResult {
  content: Array<{ type: "text"; text: string }>;
  isError?: boolean;
}

/**
 * OpenXE 1.13 REST v1 has no POST /v1/artikel (the route is commented out in
 * ApiApplication.php). Article creation therefore uses the Legacy action
 * ArtikelCreate. It is the only Legacy write in this server; it is kept here
 * so the rest of the server stays on REST.
 */
const ARTIKELKATEGORIE_TYP_EXT: Record<string, string> = {
  handelsware: "1",
};

export const PurchasePriceInput = z
  .object({
    preis: z.number().nonnegative().describe("Purchase price per unit"),
    waehrung: z.string().length(3).default("CHF").describe("Currency code, e.g. CHF or EUR"),
    ab_menge: z.number().positive().default(1).describe("Minimum quantity for this price (default 1)"),
    lieferantennummer: z.string().optional().describe("Supplier number of an existing supplier"),
    lieferantname: z
      .string()
      .optional()
      .describe("Supplier name. If no supplier with lieferantennummer exists, a supplier with this name is created."),
    bestellnummer: z.string().optional().describe("Supplier's article number"),
    bezeichnunglieferant: z.string().optional().describe("Article name as the supplier uses it"),
  })
  .refine((p) => Boolean(p.lieferantennummer || p.lieferantname), {
    message: "einkaufspreis needs lieferantennummer or lieferantname",
  });

export const ArticleCreateInput = z.object({
  name_de: z.string().min(1).describe("Article name (German)"),
  nummer: z.string().min(1).describe("Article number, e.g. 1K102. Set by you, not generated by the ERP."),
  artikelkategorie: z
    .string()
    .min(1)
    .describe("Article category. Known names: 'Handelsware'. Or pass the numeric category id as a string."),
  standardlieferant: z
    .number()
    .int()
    .positive()
    .optional()
    .describe("Address ID of the standard supplier (stored on the article as adresse)."),
  hersteller: z.string().optional().describe("Manufacturer name"),
  herstellernummer: z.string().optional().describe("Manufacturer article number"),
  ean: z.string().optional().describe("EAN / GTIN"),
  zolltarifnummer: z.string().optional().describe("Customs tariff number (HS code)"),
  herkunftsland: z.string().length(2).optional().describe("Country of origin, ISO 3166-1 alpha-2 (e.g. CH)"),
  lagerartikel: z.boolean().optional().describe("Stocked item (true) or not (false)"),
  einkaufspreis: PurchasePriceInput.optional().describe(
    "Purchase price from a supplier. Creates the supplier if it does not exist yet (by lieferantname). Requires the OpenXE fix for nested sections in ArtikelCreate."
  ),
});

export const ARTICLE_TOOL_DEFINITIONS: ToolDefinition[] = [
  {
    name: "openxe-create-article",
    description:
      "Create an article in OpenXE. Uses the Legacy API action ArtikelCreate (REST v1 has no article POST in OpenXE 1.13). " +
      "Required: name_de, nummer, artikelkategorie. Optional: standardlieferant (address ID), hersteller, herstellernummer, ean, zolltarifnummer, herkunftsland, lagerartikel. " +
      "Without confirm: true the call only returns a dry-run preview and writes nothing.",
    inputSchema: zodToJsonSchema(
      ArticleCreateInput.extend({
        confirm: z.boolean().optional().describe("Must be true to create. Without it the call only returns a dry-run preview."),
      })
    ) as Record<string, unknown>,
    annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false },
  },
];

export function articleTypExt(artikelkategorie: string): string {
  const key = artikelkategorie.trim().toLowerCase();
  return ARTIKELKATEGORIE_TYP_EXT[key] ?? artikelkategorie.trim();
}

export function buildArticlePayload(input: z.infer<typeof ArticleCreateInput>): Record<string, unknown> {
  const payload: Record<string, unknown> = {
    name_de: input.name_de.trim(),
    nummer: input.nummer.trim(),
    typ_ext: articleTypExt(input.artikelkategorie),
  };
  if (input.standardlieferant !== undefined) payload.adresse = String(input.standardlieferant);
  if (input.hersteller) payload.hersteller = input.hersteller.trim();
  if (input.herstellernummer) payload.herstellernummer = input.herstellernummer.trim();
  if (input.ean) payload.ean = input.ean.trim();
  if (input.zolltarifnummer) payload.zolltarifnummer = input.zolltarifnummer.trim();
  if (input.herkunftsland) payload.herkunftsland = input.herkunftsland.trim().toUpperCase();
  if (input.lagerartikel !== undefined) payload.lagerartikel = input.lagerartikel ? "1" : "0";
  if (input.einkaufspreis) {
    const p = input.einkaufspreis;
    payload.einkaufspreise = {
      staffelpreis: {
        ab_menge: String(p.ab_menge),
        preis: String(p.preis),
        waehrung: p.waehrung.toUpperCase(),
        lieferantennummer: p.lieferantennummer ?? "",
        lieferantname: p.lieferantname ?? "",
        bestellnummer: p.bestellnummer ?? "",
        bezeichnunglieferant: p.bezeichnunglieferant ?? input.name_de.trim(),
      },
    };
  }
  return payload;
}

export async function handleArticleTool(
  toolName: string,
  args: Record<string, unknown>,
  client: OpenXEClient
): Promise<ToolResult> {
  switch (toolName) {
    case "openxe-create-article": {
      const raw = { ...(args as Record<string, unknown>) };
      const confirm = raw.confirm === true;
      delete raw.confirm;
      const input = ArticleCreateInput.parse(raw);
      const payload = buildArticlePayload(input);

      if (!confirm) {
        return {
          content: [
            {
              type: "text",
              text: JSON.stringify(
                {
                  dry_run: true,
                  message: "Nothing was created. Repeat the call with confirm: true to create this article.",
                  transport: "Legacy API ArtikelCreate (no REST route for articles in OpenXE 1.13)",
                  would_send: payload,
                },
                null,
                2
              ),
            },
          ],
        };
      }

      const result = await client.legacyPost("ArtikelCreate", payload);
      return {
        content: [{ type: "text", text: JSON.stringify(result, null, 2) }],
      };
    }
    default:
      throw new Error(`Unknown article tool: ${toolName}`);
  }
}
